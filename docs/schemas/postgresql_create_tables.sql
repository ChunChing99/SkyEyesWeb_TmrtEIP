-- ----------------------------------------------------------------------------
-- SYS_tbScheduleTrigger（排程觸發程序表）— 一個工作可有多個觸發程序
-- ----------------------------------------------------------------------------
CREATE TABLE SYS_tbScheduleTrigger (
    TaskName               varchar(50)  NOT NULL REFERENCES SYS_tbSchedule (TaskName) ON DELETE CASCADE,
    TriggerSeq             smallint     NOT NULL,
    Enabled                varchar(1)   NOT NULL DEFAULT 'Y',
    TriggerType            varchar(10)  NOT NULL,
    StartBoundary          timestamp    NOT NULL,
    EndBoundary            timestamp,
    RecurEvery             integer      NOT NULL DEFAULT 1,
    DaysOfWeek             smallint,
    MonthsOfYear           smallint,
    DaysOfMonth            varchar(100),
    RepeatIntervalMinutes  integer,
    RepeatDurationMinutes  integer,
    RandomDelayMinutes     integer      NOT NULL DEFAULT 0,
    NextRunTime            timestamp,
    LastRunTime            timestamp,
    PRIMARY KEY (TaskName, TriggerSeq),
    CONSTRAINT ck_sys_tbscheduletrigger_enabled  CHECK (Enabled IN ('Y', 'N')),
    CONSTRAINT ck_sys_tbscheduletrigger_type     CHECK (TriggerType IN ('ONCE', 'DAILY', 'WEEKLY', 'MONTHLY', 'STARTUP')),
    CONSTRAINT ck_sys_tbscheduletrigger_boundary CHECK (EndBoundary IS NULL OR EndBoundary >= StartBoundary),
    CONSTRAINT ck_sys_tbscheduletrigger_recur    CHECK (RecurEvery > 0),
    CONSTRAINT ck_sys_tbscheduletrigger_weekly   CHECK (TriggerType <> 'WEEKLY' OR (DaysOfWeek BETWEEN 1 AND 127)),
    CONSTRAINT ck_sys_tbscheduletrigger_monthly  CHECK (TriggerType <> 'MONTHLY' OR (MonthsOfYear BETWEEN 1 AND 4095 AND DaysOfMonth IS NOT NULL AND DaysOfMonth <> '')),
    CONSTRAINT ck_sys_tbscheduletrigger_repeat   CHECK (RepeatIntervalMinutes IS NULL OR RepeatIntervalMinutes > 0),
    CONSTRAINT ck_sys_tbscheduletrigger_duration CHECK (RepeatDurationMinutes IS NULL OR (RepeatIntervalMinutes IS NOT NULL AND RepeatDurationMinutes > RepeatIntervalMinutes)),
    CONSTRAINT ck_sys_tbscheduletrigger_delay    CHECK (RandomDelayMinutes >= 0)
);

COMMENT ON TABLE  SYS_tbScheduleTrigger                       IS '排程觸發程序表（仿 Windows 工作排程器的觸發程序）';
COMMENT ON COLUMN SYS_tbScheduleTrigger.TaskName              IS '工作名稱 (PK，FK: SYS_tbSchedule.TaskName)';
COMMENT ON COLUMN SYS_tbScheduleTrigger.TriggerSeq            IS '觸發程序序號 (PK)';
COMMENT ON COLUMN SYS_tbScheduleTrigger.Enabled               IS '此觸發程序是否啟用 (Y/N)';
COMMENT ON COLUMN SYS_tbScheduleTrigger.TriggerType           IS 'ONCE（一次）／DAILY（每天）／WEEKLY（每週）／MONTHLY（每月）／STARTUP（服務啟動時）';
COMMENT ON COLUMN SYS_tbScheduleTrigger.StartBoundary         IS '開始時間：首次生效日期與每次執行的時間點';
COMMENT ON COLUMN SYS_tbScheduleTrigger.EndBoundary           IS '到期時間；NULL 代表永不到期';
COMMENT ON COLUMN SYS_tbScheduleTrigger.RecurEvery            IS 'DAILY：每 N 天；WEEKLY：每 N 週；其他類型忽略';
COMMENT ON COLUMN SYS_tbScheduleTrigger.DaysOfWeek            IS 'WEEKLY 位元遮罩：週日=1、週一=2、週二=4、週三=8、週四=16、週五=32、週六=64';
COMMENT ON COLUMN SYS_tbScheduleTrigger.MonthsOfYear          IS 'MONTHLY 位元遮罩：1 月=1 … 12 月=2048；全選 4095';
COMMENT ON COLUMN SYS_tbScheduleTrigger.DaysOfMonth           IS 'MONTHLY 逗號分隔日期，L 代表當月最後一天，如 1,15,L';
COMMENT ON COLUMN SYS_tbScheduleTrigger.RepeatIntervalMinutes IS '重複工作間隔（分鐘）';
COMMENT ON COLUMN SYS_tbScheduleTrigger.RepeatDurationMinutes IS '重複持續時間（分鐘）；RepeatIntervalMinutes 有值而此欄 NULL 代表無限期重複';
COMMENT ON COLUMN SYS_tbScheduleTrigger.RandomDelayMinutes    IS '隨機延遲上限（分鐘）';
COMMENT ON COLUMN SYS_tbScheduleTrigger.NextRunTime           IS '下次預計執行時間；NULL 代表已無下次';
COMMENT ON COLUMN SYS_tbScheduleTrigger.LastRunTime           IS '此觸發程序上次觸發時間';

-- 供 Worker 輪詢到期觸發程序
CREATE INDEX ix_sys_tbscheduletrigger_nextrun ON SYS_tbScheduleTrigger (NextRunTime) WHERE Enabled = 'Y';

