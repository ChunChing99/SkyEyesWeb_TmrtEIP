-- ----------------------------------------------------------------------------
-- SYS_tbPasswordValidationRules（密碼驗證規則表）
-- ----------------------------------------------------------------------------
CREATE TABLE SYS_tbPasswordValidationRules (
    Id                              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
