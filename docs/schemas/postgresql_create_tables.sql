CREATE OR REPLACE FUNCTION wf_validate_definenodeapprover_gateway()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_define_id varchar(40);
    target_version_no integer;
BEGIN
    target_define_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.DefineId ELSE NEW.DefineId END;
    target_version_no := CASE WHEN TG_OP = 'DELETE' THEN OLD.VersionNo ELSE NEW.VersionNo END;

    IF EXISTS (
        SELECT 1
        FROM WF_tbDefineNode
        WHERE DefineId = target_define_id
          AND VersionNo = target_version_no
          AND NodeCode = CASE WHEN TG_OP = 'DELETE' THEN OLD.NodeCode ELSE NEW.NodeCode END
          AND NodeType = 'Gateway'
    ) THEN
        RAISE EXCEPTION 'Gateway 節點不可配置簽核人';
    END IF;

    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

