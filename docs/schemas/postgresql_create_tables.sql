COMMENT ON COLUMN SYS_tbPasswordValidationRules.MinLowercaseLength           IS '小寫英文最小長度';
COMMENT ON COLUMN SYS_tbPasswordValidationRules.MinSpecialCharLength         IS '特殊符號最小長度';
COMMENT ON COLUMN SYS_tbPasswordValidationRules.MinNumericLength             IS '數字最小長度';
COMMENT ON COLUMN SYS_tbPasswordValidationRules.TokenLimit                   IS 'Token期限(分鐘)';
COMMENT ON COLUMN SYS_tbPasswordValidationRules.MaxFailedLogin               IS '登入失敗次數上限';
COMMENT ON COLUMN SYS_tbPasswordValidationRules.AccountLockoutTime           IS '帳號鎖定時間(分鐘)';
COMMENT ON COLUMN SYS_tbPasswordValidationRules.IsActive                     IS '是否啟用';
COMMENT ON COLUMN SYS_tbPasswordValidationRules.update_dt                    IS '更新時間';
