COMMENT ON COLUMN SYS_tbPasswordValidationRules.RuleName                     IS '名稱';
COMMENT ON COLUMN SYS_tbPasswordValidationRules.MinLength                    IS '密碼最小長度';
COMMENT ON COLUMN SYS_tbPasswordValidationRules.PasswordChangeFrequencyDays  IS '密碼更新頻率';
