-- ----------------------------------------------------------------------------
-- SYS_ttIssuedSerialNumber（已發行序號紀錄表）
-- 不是計數器，而是每發行一個號碼即一列：PK 為 (DocType, OrgCode, PeriodKey, Seq)，
-- 同一個號碼不可能被插入兩列，由資料庫主鍵約束本身物理上保證不會重複發放，
-- 且本表逐筆記錄「誰在何時拿到哪個號碼」，本身就是完整的發行歷程。
-- 見 docs/schemas/database_schema.md「編碼/序號管理資料表」。
-- ----------------------------------------------------------------------------
CREATE TABLE SYS_ttIssuedSerialNumber (
    DocType         varchar(4)   NOT NULL,
    OrgCode         varchar(10)  NOT NULL DEFAULT '',
    PeriodKey       varchar(8)   NOT NULL,
    Seq             integer      NOT NULL,
    IssuedCode      varchar(50)  NOT NULL,
    IssuedUser_No   varchar(20),
    IssuedTime      timestamp    NOT NULL DEFAULT now(),
    PRIMARY KEY (DocType, OrgCode, PeriodKey, Seq),
    UNIQUE (IssuedCode)
);

COMMENT ON TABLE  SYS_ttIssuedSerialNumber                  IS '已發行序號紀錄表';
COMMENT ON COLUMN SYS_ttIssuedSerialNumber.DocType          IS '業務/單據類型碼 (PK)，2~4 碼，如 PA、DRAW、LEAVE';
COMMENT ON COLUMN SYS_ttIssuedSerialNumber.OrgCode          IS '發起組織/部門代碼 (PK)，選填，如 HQ、RD、TC；不分部門時為空字串（哨兵值，非 NULL）';
COMMENT ON COLUMN SYS_ttIssuedSerialNumber.PeriodKey        IS '日期序列碼 (PK)，固定 8 碼，格式統一為 YYYYMMDD（每日歸零重新編號）';
COMMENT ON COLUMN SYS_ttIssuedSerialNumber.Seq              IS '動態流水號 (PK)，本次實際發出的號碼';
COMMENT ON COLUMN SYS_ttIssuedSerialNumber.IssuedCode       IS '完整編號字串，如 PA-RD-20260911-0042；保留當時實際發出的樣子，不受日後格式樣板變更影響';
COMMENT ON COLUMN SYS_ttIssuedSerialNumber.IssuedUser_No    IS '開立帳號；邏輯參照 SYS_tbUser.User_No，比照 SYS_ttLog.User_No 慣例，背景排程觸發時可為空，未建立強制 FK';
COMMENT ON COLUMN SYS_ttIssuedSerialNumber.IssuedTime       IS '發行時間';

