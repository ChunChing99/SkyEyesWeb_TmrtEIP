-- WF_ttProcessSign（簽核意見與紀錄表）
-- 純粹的執行期歷程紀錄，只允許 INSERT，不允許 UPDATE/DELETE；不設 update_dt/update_user，也不另設
-- insert_dt/insert_user，SignTime/ApproveUser_No 即為建立時間/建立人。
-- ApproveUser_No 為 NULL 代表系統產生的撤回、跳過或逾時事件（比照 SYS_ttIssuedSerialNumber.
-- IssuedUser_No「背景排程觸發時可為空」慣例，不寫入 'SYSTEM' 之類字面值哨兵，
-- 否則會違反下方對 WF_ttProcessNodeAssignee 的複合 FK）；PostgreSQL 複合 FK
-- 預設 MATCH SIMPLE，ApproveUser_No 為 NULL 時會略過該筆 FK 檢查。
-- ----------------------------------------------------------------------------
CREATE TABLE WF_ttProcessSign (
    Id              varchar(40)  NOT NULL REFERENCES WF_ttProcess (Id),
    NodeCode        varchar(20)  NOT NULL,
    SignSeq         integer      NOT NULL,
    ApproveUser_No  varchar(20),
    SignStatus      varchar(20)  NOT NULL,
    SignComment     varchar(500),
    Signature       bytea,
    SignTime        timestamp    NOT NULL DEFAULT now(),
    TimeoutAction   varchar(20),
    PRIMARY KEY (Id, NodeCode, SignSeq),
    CONSTRAINT ck_wf_ttprocesssign_signseq CHECK (SignSeq > 0),
    CONSTRAINT ck_wf_ttprocesssign_signstatus
        CHECK (SignStatus IN ('APPROVE', 'REJECT', 'TRANSFER', 'WITHDRAW', 'SKIP', 'TIMEOUT')),
    CONSTRAINT ck_wf_ttprocesssign_timeoutaction
        CHECK (
            (SignStatus = 'TIMEOUT' AND TimeoutAction IN ('RETURN_TO_INITIATOR', 'FORWARD_TO_SUPERIOR', 'AUTO_APPROVE_NEXT'))
            OR (SignStatus <> 'TIMEOUT' AND TimeoutAction IS NULL)
        ),
    CONSTRAINT fk_wf_ttprocesssign_node
        FOREIGN KEY (Id, NodeCode)
        REFERENCES WF_ttProcessNode (Id, NodeCode),
    CONSTRAINT fk_wf_ttprocesssign_assignee
        FOREIGN KEY (Id, NodeCode, ApproveUser_No)
        REFERENCES WF_ttProcessNodeAssignee (Id, NodeCode, ApproveUser_No)
);

COMMENT ON TABLE  WF_ttProcessSign                  IS '簽核意見與紀錄表；append-only，只允許 INSERT，禁止 UPDATE/DELETE；為逐人簽核狀態的唯一歷程來源';
COMMENT ON COLUMN WF_ttProcessSign.Id               IS '所屬流程實例鍵 (PK，FK: WF_ttProcess.Id)';
COMMENT ON COLUMN WF_ttProcessSign.NodeCode         IS '關卡代碼 (PK)';
COMMENT ON COLUMN WF_ttProcessSign.SignSeq          IS '簽核流水號 (PK)，同一關卡下第幾筆簽核紀錄，由 1 起算';
COMMENT ON COLUMN WF_ttProcessSign.ApproveUser_No   IS '實際簽核人員帳號；系統產生的撤回/跳過/逾時事件可為 NULL (與 Id, NodeCode 組成 FK: WF_ttProcessNodeAssignee)';
COMMENT ON COLUMN WF_ttProcessSign.SignStatus       IS '簽核事件：APPROVE(同意)/REJECT(退件)/TRANSFER(轉簽)/WITHDRAW(撤回)/SKIP(跳過)/TIMEOUT(逾時)';
COMMENT ON COLUMN WF_ttProcessSign.SignComment      IS '簽核意見/評語';
COMMENT ON COLUMN WF_ttProcessSign.Signature        IS '自然人憑證數位簽章';
COMMENT ON COLUMN WF_ttProcessSign.SignTime         IS '簽核時間';
COMMENT ON COLUMN WF_ttProcessSign.TimeoutAction    IS '逾時處理類型；SignStatus=TIMEOUT 時必填，其他事件必須為 NULL：RETURN_TO_INITIATOR/FORWARD_TO_SUPERIOR/AUTO_APPROVE_NEXT';

-- 同一流程/關卡/簽核人的第一筆人工簽核事件由部分唯一索引保證；
-- 不同簽核人可在 AndSign 等模式下各自寫入事件，節點完成條件仍由應用層分析。

CREATE OR REPLACE FUNCTION wf_prevent_processsign_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'WF_ttProcessSign 僅允許 INSERT，不允許 UPDATE 或 DELETE';
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_wf_ttprocesssign_prevent_change
BEFORE UPDATE OR DELETE ON WF_ttProcessSign
FOR EACH ROW
EXECUTE FUNCTION wf_prevent_processsign_change();

CREATE UNIQUE INDEX ux_wf_ttprocesssign_first_user_action
        ON WF_ttProcessSign (Id, NodeCode, ApproveUser_No)
        WHERE ApproveUser_No IS NOT NULL
            AND SignStatus IN ('APPROVE', 'REJECT', 'TRANSFER');

CREATE INDEX ix_wf_ttprocesssign_approveuserno ON WF_ttProcessSign (ApproveUser_No);
CREATE INDEX ix_wf_ttprocesssign_status        ON WF_ttProcessSign (SignStatus);

