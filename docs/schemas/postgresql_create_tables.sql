-- ----------------------------------------------------------------------------
-- SYS_tbSchedule（排程工作表）— 仿 Windows 工作排程器，供 BackgroundWorker 輪詢執行
-- ----------------------------------------------------------------------------
CREATE TABLE SYS_tbSchedule (
    TaskName                   varchar(50)  PRIMARY KEY,
    Description                varchar(200),
    Enabled                    varchar(1)   NOT NULL DEFAULT 'Y',
    HandlerName                varchar(100) NOT NULL,
    Parameters                 text,
    MultipleInstancePolicy     varchar(15)  NOT NULL DEFAULT 'IGNORE_NEW',
    ExecutionTimeLimitMinutes  integer      DEFAULT 4320,
    RestartCount               integer      NOT NULL DEFAULT 0,
    RestartIntervalMinutes     integer,
    RunMissed                  varchar(1)   NOT NULL DEFAULT 'Y',
    ForceRun                   varchar(1)   NOT NULL DEFAULT 'N',
    LastRunTime                timestamp,
    LastRunResult              varchar(10),
    LastRunMessage             text,
    LockedBy                   varchar(100),
    LockedUntil                timestamp,
    CreateDate                 timestamp    NOT NULL DEFAULT now(),
    UpdateDate                 timestamp    NOT NULL DEFAULT now(),
    CONSTRAINT ck_sys_tbschedule_enabled   CHECK (Enabled IN ('Y', 'N')),
    CONSTRAINT ck_sys_tbschedule_runmissed CHECK (RunMissed IN ('Y', 'N')),
    CONSTRAINT ck_sys_tbschedule_forcerun  CHECK (ForceRun IN ('Y', 'N')),
    CONSTRAINT ck_sys_tbschedule_policy    CHECK (MultipleInstancePolicy IN ('IGNORE_NEW', 'PARALLEL')),
    CONSTRAINT ck_sys_tbschedule_timelimit CHECK (ExecutionTimeLimitMinutes IS NULL OR ExecutionTimeLimitMinutes > 0),
    CONSTRAINT ck_sys_tbschedule_restart   CHECK (RestartCount >= 0 AND (RestartCount = 0 OR RestartIntervalMinutes > 0)),
    CONSTRAINT ck_sys_tbschedule_result    CHECK (LastRunResult IS NULL OR LastRunResult IN ('RUNNING', 'SUCCESS', 'FAIL', 'TIMEOUT'))
